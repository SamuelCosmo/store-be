-- Baseline schema for SAC+ (Store Platform).
-- Idempotent so `baseline-on-migrate: true` + `baseline-version: 0` safely
-- adopts pre-Flyway databases while building empty databases from scratch.

CREATE TABLE IF NOT EXISTS clients (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(255) NOT NULL,
    logo_url            VARCHAR(255),
    max_stores          INTEGER NOT NULL,
    max_pos_per_store   INTEGER NOT NULL,
    max_kiosks_per_store INTEGER NOT NULL,
    currency            VARCHAR(3),
    tax_rate            NUMERIC(38, 2),
    token_price         NUMERIC(38, 2),
    kiosk_receipt_seconds INTEGER,
    session_hours       JSONB,
    timezone            VARCHAR(64),
    created_at          TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS client_modules (
    client_id BIGINT NOT NULL REFERENCES clients(id),
    module    VARCHAR(32) NOT NULL,
    PRIMARY KEY (client_id, module),
    CONSTRAINT client_modules_module_check CHECK (module IN (
        'CATALOG', 'INVENTORY', 'POS', 'KIOSK', 'KDS',
        'BAR', 'TOKENS', 'REPORTS', 'TICKETS', 'RESERVATIONS'
    ))
);

CREATE TABLE IF NOT EXISTS stores (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id        BIGINT NOT NULL REFERENCES clients(id),
    name             VARCHAR(255) NOT NULL,
    description      VARCHAR(255),
    address          VARCHAR(255),
    business_type    VARCHAR(255) NOT NULL,
    active           BOOLEAN NOT NULL DEFAULT TRUE,
    menu_name        VARCHAR(255),
    kitchen_ok_min   INTEGER,
    kitchen_warn_min INTEGER,
    kitchen_sound    BOOLEAN,
    logo_url         VARCHAR(255),
    primary_color    VARCHAR(255),
    accent_color     VARCHAR(255),
    canvas_color     VARCHAR(255),
    created_at       TIMESTAMPTZ NOT NULL,
    deleted_at       TIMESTAMPTZ,
    CONSTRAINT stores_business_type_check CHECK (business_type IN (
        'RESTAURANT', 'RETAIL', 'BAR', 'CAFE'
    ))
);

CREATE TABLE IF NOT EXISTS devices (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id BIGINT NOT NULL REFERENCES stores(id),
    name     VARCHAR(255) NOT NULL,
    type     VARCHAR(255) NOT NULL,
    active   BOOLEAN NOT NULL,
    CONSTRAINT devices_type_check CHECK (type IN ('POS', 'KIOSK'))
);

CREATE TABLE IF NOT EXISTS users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id     BIGINT REFERENCES clients(id),
    name          VARCHAR(255) NOT NULL,
    email         VARCHAR(255) NOT NULL UNIQUE,
    password      VARCHAR(255) NOT NULL,
    role          VARCHAR(255) NOT NULL,
    active        BOOLEAN NOT NULL DEFAULT TRUE,
    token_version INTEGER NOT NULL DEFAULT 0,
    created_at    TIMESTAMPTZ NOT NULL,
    deleted_at    TIMESTAMPTZ,
    CONSTRAINT users_role_check CHECK (role IN (
        'ADMIN', 'MANAGER', 'EMPLOYEE', 'CUSTOMER', 'KITCHEN', 'SUPERADMIN'
    ))
);

CREATE TABLE IF NOT EXISTS user_stores (
    user_id  BIGINT NOT NULL REFERENCES users(id),
    store_id BIGINT NOT NULL REFERENCES stores(id),
    PRIMARY KEY (user_id, store_id)
);

CREATE TABLE IF NOT EXISTS user_modules (
    user_id BIGINT NOT NULL REFERENCES users(id),
    module  VARCHAR(32) NOT NULL,
    PRIMARY KEY (user_id, module),
    CONSTRAINT user_modules_module_check CHECK (module IN (
        'CATALOG', 'INVENTORY', 'POS', 'KIOSK', 'KDS',
        'BAR', 'TOKENS', 'REPORTS', 'TICKETS', 'RESERVATIONS'
    ))
);

CREATE TABLE IF NOT EXISTS categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    description VARCHAR(255),
    icon        VARCHAR(255),
    active      BOOLEAN NOT NULL DEFAULT TRUE,
    deleted_at  TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS category_stores (
    category_id BIGINT NOT NULL REFERENCES categories(id),
    store_id    BIGINT NOT NULL REFERENCES stores(id),
    PRIMARY KEY (category_id, store_id)
);

CREATE TABLE IF NOT EXISTS products (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL REFERENCES categories(id),
    name        VARCHAR(255) NOT NULL,
    description VARCHAR(255),
    sku         VARCHAR(255),
    image       VARCHAR(255),
    price       NUMERIC(38, 2) NOT NULL,
    active      BOOLEAN NOT NULL,
    sold_out    BOOLEAN NOT NULL DEFAULT FALSE,
    token_cost  INTEGER NOT NULL,
    deleted_at  TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS extras (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id  BIGINT NOT NULL REFERENCES clients(id),
    name       VARCHAR(255) NOT NULL,
    price      NUMERIC(38, 2) NOT NULL,
    active     BOOLEAN NOT NULL,
    deleted_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS sizes (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id  BIGINT NOT NULL REFERENCES clients(id),
    name       VARCHAR(255) NOT NULL,
    price      NUMERIC(38, 2) NOT NULL,
    active     BOOLEAN NOT NULL,
    "position" INTEGER,
    deleted_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS product_extras (
    product_id BIGINT NOT NULL REFERENCES products(id),
    extra_id   BIGINT NOT NULL REFERENCES extras(id),
    PRIMARY KEY (product_id, extra_id)
);

CREATE TABLE IF NOT EXISTS product_sizes (
    product_id BIGINT NOT NULL REFERENCES products(id),
    size_id    BIGINT NOT NULL REFERENCES sizes(id),
    PRIMARY KEY (product_id, size_id)
);

CREATE TABLE IF NOT EXISTS inventory (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL UNIQUE REFERENCES products(id),
    quantity   INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS orders (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id        BIGINT NOT NULL REFERENCES stores(id),
    user_id         BIGINT NOT NULL REFERENCES users(id),
    channel         VARCHAR(255) NOT NULL,
    order_type      VARCHAR(255) NOT NULL,
    payment_method  VARCHAR(255) NOT NULL,
    status          VARCHAR(255) NOT NULL,
    refund_status   VARCHAR(255) NOT NULL,
    total           NUMERIC(38, 2) NOT NULL,
    subtotal        NUMERIC(38, 2),
    tax_rate        NUMERIC(38, 2),
    tax_amount      NUMERIC(38, 2),
    ticket_number   INTEGER,
    cash_received   NUMERIC(38, 2),
    change_given    NUMERIC(38, 2),
    token_amount    INTEGER,
    idempotency_key VARCHAR(64),
    created_at      TIMESTAMPTZ NOT NULL,
    version         BIGINT NOT NULL DEFAULT 0,
    cancelled_by    BIGINT REFERENCES users(id),
    cancelled_at    TIMESTAMPTZ,
    ready_at        TIMESTAMPTZ,
    completed_at    TIMESTAMPTZ,
    CONSTRAINT uk_orders_store_idempotency UNIQUE (store_id, idempotency_key),
    CONSTRAINT orders_channel_check CHECK (channel IN ('POS', 'KIOSK')),
    CONSTRAINT orders_order_type_check CHECK (order_type IN ('DINE_IN', 'TAKEAWAY')),
    CONSTRAINT orders_payment_method_check CHECK (payment_method IN ('CASH', 'CARD', 'TOKEN')),
    CONSTRAINT orders_refund_status_check CHECK (refund_status IN ('NONE', 'REFUNDED')),
    CONSTRAINT orders_status_check CHECK (status IN (
        'PENDING', 'CONFIRMED', 'PREPARING', 'READY', 'COMPLETED', 'CANCELLED'
    ))
);

CREATE TABLE IF NOT EXISTS order_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT NOT NULL REFERENCES orders(id),
    product_id BIGINT NOT NULL REFERENCES products(id),
    quantity   INTEGER NOT NULL,
    unit_price NUMERIC(38, 2) NOT NULL,
    token_cost INTEGER,
    size_name  VARCHAR(255),
    extras     JSONB,
    notes      TEXT
);

CREATE TABLE IF NOT EXISTS token_sales (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id        BIGINT NOT NULL REFERENCES stores(id),
    user_id         BIGINT NOT NULL REFERENCES users(id),
    quantity        INTEGER NOT NULL,
    unit_price      NUMERIC(38, 2) NOT NULL,
    total_price     NUMERIC(38, 2) NOT NULL,
    payment_method  VARCHAR(255) NOT NULL,
    idempotency_key VARCHAR(64),
    created_at      TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_token_sales_store_idempotency UNIQUE (store_id, idempotency_key),
    CONSTRAINT token_sales_payment_method_check CHECK (payment_method IN ('CASH', 'CARD', 'TOKEN'))
);

CREATE TABLE IF NOT EXISTS audit_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id    BIGINT REFERENCES clients(id),
    store_id     BIGINT REFERENCES stores(id),
    actor_id     BIGINT,
    actor_name   VARCHAR(255),
    actor_email  VARCHAR(255),
    actor_role   VARCHAR(255),
    entity_type  VARCHAR(40) NOT NULL,
    action       VARCHAR(40) NOT NULL,
    entity_id    BIGINT,
    entity_label VARCHAR(255),
    details      JSONB,
    created_at   TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_audit_events_client_created ON audit_events (client_id, created_at);
CREATE INDEX IF NOT EXISTS idx_audit_events_entity_type ON audit_events (entity_type);
CREATE INDEX IF NOT EXISTS idx_audit_events_actor_id ON audit_events (actor_id);

CREATE TABLE IF NOT EXISTS app_logs (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL,
    level      VARCHAR(5) NOT NULL,
    logger     VARCHAR(120),
    message    TEXT,
    stack      TEXT,
    request_id VARCHAR(64),
    user_id    BIGINT,
    client_id  BIGINT,
    store_id   BIGINT,
    role       VARCHAR(20)
);

CREATE INDEX IF NOT EXISTS idx_app_logs_created_at ON app_logs (created_at);
CREATE INDEX IF NOT EXISTS idx_app_logs_request_id ON app_logs (request_id);
